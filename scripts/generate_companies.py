# MAIN PROCESSING LOGIC
# ═══════════════════════════════════════════════════════════════════════════════

def main():
    companies = []
    seen = set()

    for category, entries in DATA.items():
        for entry in entries:
            if isinstance(entry, tuple) and len(entry) == 2:
                name, url = entry
                key = name.lower().strip()
                if key not in seen:
                    seen.add(key)
                    companies.append({
                        "name": name,
                        "careers_url": url,
                        "category": category
                    })
            else:
                print(f"WARNING: Invalid entry in {category}: {entry}")

    companies.sort(key=lambda x: x["name"].lower())

    with open("audio_companies.json", "w", encoding="utf-8") as f:
        json.dump(companies, f, indent=2, ensure_ascii=False)

    # Print stats
    print(f"\nTotal companies: {len(companies)}")
    print("\nCompanies per category:")
    from collections import Counter
    cat_counts = Counter(c["category"] for c in companies)
    for cat, count in sorted(cat_counts.items(), key=lambda x: -x[1]):
        print(f"  {cat}: {count}")

